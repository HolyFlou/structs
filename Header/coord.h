/**
 * @brief Структура для представлення 2D-координат.
 *
 * @details Містить цілочисельні координати по осях X та Y.
 */
typedef struct {
    int x;
    int y;
} coord;

/**
 * @brief Виводить координати точки в консоль.
 *
 * @details Приймає структуру coord за значенням та виводить її поля x та y
 * у форматованому вигляді.
 *
 * @param c Структура coord, значення якої потрібно вивести.
 */
void print_coord(coord c);

/**
 * @brief Обчислює суму двох координат.
 *
 * @details Додає відповідні компоненти (x1 + x2, y1 + y2) двох точок
 * та повертає нову структуру coord із результатами.
 *
 * @param c1 Перша точка (структура coord).
 * @param c2 Друга точка (структура coord).
 *
 * @return Результуюча точка (coord), яка містить суму координат.
 */
coord add_coords(coord c1, coord c2);